"""Load, resolve, map and emit: JSON Schema in, TypeScript source out."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .errors import SchemaError
from .loader import load_schema
from .mapper import Options, TypeBuilder
from .resolver import Document


@dataclass
class Result:
    """Generated source plus anything that was skipped on the way."""

    code: str
    warnings: list[str] = field(default_factory=list)
    names: list[str] = field(default_factory=list)
    dependencies: list[Path] = field(default_factory=list)  # other files read via $ref


def banner(source: str | None) -> str:
    origin = f" from {source}" if source else ""
    return (
        "/* eslint-disable */\n"
        "/**\n"
        f" * This file was generated by schemaflow{origin}.\n"
        " * Do not edit it by hand: changes are overwritten the next time it is generated.\n"
        " */\n"
    )


def generate(
    schema: Any, path: Path | None = None, options: Options | None = None, source: str | None = None
) -> Result:
    """Generate TypeScript for an already parsed schema.

    ``path`` is the file it came from; it is needed to resolve ``$ref`` to other files.
    ``source`` is the name shown in the header (defaults to the file name).
    """
    options = options or Options()
    if not isinstance(schema, (dict, bool)):
        raise SchemaError("a schema must be a JSON object or boolean", path)
    document = Document(schema, path.resolve() if path else None)
    builder = TypeBuilder(document, options)
    declarations = builder.build()
    body = "\n\n".join(declarations) + "\n"
    code = body
    if options.banner:
        origin = source if source is not None else (path.name if path else None)
        code = banner(origin) + "\n" + body
    return Result(code, builder.warnings, builder.declared, builder.resolver.loaded_paths())


def generate_from_path(path: str | Path, options: Options | None = None) -> Result:
    """Generate TypeScript for the schema in ``path``."""
    target = Path(path)
    return generate(load_schema(target), target, options)


def generate_ts_from_path(path: str | Path, options: Options | None = None) -> str:
    """Convenience wrapper returning only the TypeScript source."""
    return generate_from_path(path, options).code


def generate_ts(schema: Any, name: str | None = None, options: Options | None = None) -> str:
    """TypeScript for a schema held in memory, without a header banner by default."""
    options = options or Options(banner=False)
    if name:
        options.name = name
    return generate(schema, None, options).code
